// Two audits of the finished atlas data, written to tools/source/audit_settlements.md and audit_travel.md:
//  1. settlement siting: does each town/city/port have water (sea, river, lake) close by, and is every "port" on a coast?
//  2. travel times: where the old notes give a travel time between two places, does the map distance fit it?
// usage: node audit.mjs ../atlas/data
import fs from 'node:fs';
import path from 'node:path';
import * as turf from '@turf/turf';

const dataDir = path.resolve(process.argv[2] || '../atlas/data');
const MPP = JSON.parse(fs.readFileSync(path.join(dataDir, 'scale.json'), 'utf8')).milesPerWorldPx;
const rd = (f) => JSON.parse(fs.readFileSync(path.join(dataDir, f), 'utf8')).features;
const W = ([lng, lat]) => [lng * 51.2 + 512, 512 - lat * 51.2];
const objs = JSON.parse(fs.readFileSync('../original_data/db/objects.json', 'utf8'));
const byId = new Map(objs.map((o) => [o.id, o]));

// ---- geometry in world px ----
const seg = (ring) => ring.slice(0, -1).map((a, i) => [...W(a), ...W(ring[i + 1])]);
const coastSegs = rd('land.geojson')[0].geometry.coordinates.flatMap((poly) => poly.flatMap(seg));
const riverSegs = rd('rivers.geojson').flatMap((f) => { const c = f.geometry.coordinates; return c.slice(0, -1).map((a, i) => [...W(a), ...W(c[i + 1])]); });
const lakeSegs = rd('lakes.geojson').flatMap((f) => f.geometry.coordinates.flatMap(seg));
const dSeg = (px, py, [x0, y0, x1, y1]) => { const dx = x1 - x0, dy = y1 - y0, l2 = dx * dx + dy * dy; let t = l2 ? ((px - x0) * dx + (py - y0) * dy) / l2 : 0; t = Math.max(0, Math.min(1, t)); return Math.hypot(px - x0 - t * dx, py - y0 - t * dy); };
const dist = (p, segs) => { let b = Infinity; for (const s of segs) { if (Math.abs(s[0] - p[0]) > 60 && Math.abs(s[2] - p[0]) > 60) continue; const d = dSeg(p[0], p[1], s); if (d < b) b = d; } return b; };
const mountains = rd('terrain.geojson').filter((f) => f.properties.kind === 'mountain');
const inMountains = (lnglat) => mountains.some((f) => turf.booleanPointInPolygon(lnglat, f));

// ---- 1. settlement siting ----
const places = rd('places.geojson');
const SETTLEMENT = new Set(['city', 'capital', 'town', 'port', 'village', 'hamlet']);
const rows = [];
for (const f of places) {
  const k = f.properties.kind;
  if (!SETTLEMENT.has(k)) continue;
  const p = W(f.geometry.coordinates);
  const coast = dist(p, coastSegs) * MPP, river = dist(p, riverSegs) * MPP, lake = dist(p, lakeSegs) * MPP;
  const water = Math.min(coast, river, lake);
  rows.push({ name: f.properties.name, kind: k, rank: f.properties.rank, guess: !!f.properties.guess, src: f.properties.source, coast, river, lake, water, mtn: inMountains(f.geometry.coordinates) });
}
const portsOff = rows.filter((r) => r.kind === 'port' && r.coast > 20);
const dry = rows.filter((r) => ['city', 'capital', 'town'].includes(r.kind) && r.water > 40 && !r.mtn);
const dryMtn = rows.filter((r) => ['city', 'capital', 'town'].includes(r.kind) && r.water > 40 && r.mtn);
const tag = (r) => (r.guess ? 'first-pass guess' : 'from your maps/placement');
const fmt = (r) => `- **${r.name}** (${r.kind}) — sea ${Math.round(r.coast)} mi, river ${Number.isFinite(r.river) ? Math.round(r.river) : '–'} mi, lake ${Number.isFinite(r.lake) ? Math.round(r.lake) : '–'} mi — ${tag(r)}`;
let md = `# Settlement siting audit\n\nGenerated by tools/audit.mjs. Distances are straight-line miles on the calibrated map (${MPP} mi per map pixel). ${rows.length} settlements checked (city, capital, town, port, village, hamlet).\n\n`;
md += `Rules of thumb: a port should be on a coast (within ~20 mi); a city or town normally wants sea, a river or a lake within ~40 mi (a day or two on foot) unless it is a mountain-fortress.\n\n`;
md += `## Ports not on a coast (${portsOff.length})\n\n${portsOff.map(fmt).join('\n') || '_none_'}\n\n`;
md += `## Cities and towns with no sea, river or lake within 40 miles (${dry.length})\n\n${dry.sort((a, b) => b.water - a.water).map(fmt).join('\n') || '_none_'}\n\n`;
md += `## Inland mountain cities and towns (${dryMtn.length}) — fine for dwarven holds, otherwise worth a look\n\n${dryMtn.map(fmt).join('\n') || '_none_'}\n\n`;
fs.writeFileSync('source/audit_settlements.md', md);
console.log(`settlements ${rows.length}: ports off a coast ${portsOff.length}; dry cities/towns ${dry.length}; dry mountain ones ${dryMtn.length}`);

// ---- 2. travel times in the old notes ----
const words = { a: 1, an: 1, one: 1, two: 2, three: 3, four: 4, five: 5, six: 6, seven: 7, eight: 8, nine: 9, ten: 10, twelve: 12, fortnight: 14 };
const dur = /\b(a|an|one|two|three|four|five|six|seven|eight|nine|ten|twelve|\d+)(?:\s*(?:to|or|-)\s*(?:a|one|two|three|four|five|six|seven|eight|nine|ten|\d+))?\s*(?:full\s+)?(days?|weeks?|hours?)\b|\b(a fortnight)\b/i;
const sea = /\b(sail|sailing|by sea|by ship|voyage)\b/i;
const pins = new Map(); // lowercase name -> {name, p(world px), guess, dbId}
const regions = rd('regions.geojson');
for (const f of [...places, ...regions]) {
  const nm = (f.properties.name || '').toLowerCase();
  const o = f.properties.dbId ? byId.get(f.properties.dbId) : null;
  const rec = { name: f.properties.name, p: W(f.geometry.coordinates), guess: !!f.properties.guess, dbId: f.properties.dbId, kind: f.properties.kind };
  if (nm && !pins.has(nm)) pins.set(nm, rec);
  if (o && !pins.has(o.name.toLowerCase())) pins.set(o.name.toLowerCase(), rec);
}
const policy = JSON.parse(fs.readFileSync('source/canon_policy.json', 'utf8'));
const canon = (o) => policy.canonOwners.includes(o.owner) && !policy.thirdPartyOwners.ids.includes(o.owner);
const hits = [];
for (const o of objs) {
  if (!canon(o) || !o.description) continue;
  const self = pins.get(o.name.toLowerCase());
  const text = o.description.replace(/\s+/g, ' ');
  for (const sentence of text.split(/(?<=[.!?])\s+/)) {
    const m = sentence.match(dur);
    if (!m) continue;
    let n = m[4] ? 14 : (words[m[1].toLowerCase()] ?? Number(m[1]));
    const unit = (m[2] || 'days').toLowerCase();
    let days = unit.startsWith('week') ? n * 7 : unit.startsWith('hour') ? n / 10 : n;
    if (!Number.isFinite(days) || days <= 0) continue;
    // which other places does the sentence mention?
    const lower = sentence.toLowerCase();
    const named = [...pins.keys()].filter((k) => k.length > 3 && k !== o.name.toLowerCase() && new RegExp(`\\b${k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`).test(lower));
    for (const k of named) {
      const other = pins.get(k);
      if (!self || !other || self === other) continue;
      const miles = Math.hypot(self.p[0] - other.p[0], self.p[1] - other.p[1]) * MPP;
      const by = sea.test(sentence) ? 'sea' : 'land';
      const lo = by === 'sea' ? 48 : 12, hi = by === 'sea' ? 100 : 30; // miles per day: ships 48-100; foot/wagon/horse overland 12-30
      const verdict = miles > days * hi * 1.15 ? 'map too far' : miles < days * lo * 0.7 ? 'map too close' : 'fits';
      hits.push({ from: o.name, to: other.name, days, miles, by, verdict, bothAuthor: !self.guess && !other.guess, guess: [self.guess && o.name, other.guess && other.name].filter(Boolean), sentence: sentence.slice(0, 200) });
    }
  }
}
const bad = hits.filter((h) => h.verdict !== 'fits');
let md2 = `# Travel-time audit\n\nGenerated by tools/audit.mjs. Looks in your canon notes (yours and Jacob's) for sentences giving a travel time, finds the places named in them that are on the map, and compares the map distance (${MPP} mi per map pixel) with a plausible pace: 12–30 miles a day overland, 48–100 at sea. Only straight-line distances are compared, so a winding road can legitimately run longer.\n\n${hits.length} place pairs found; **${bad.length} do not fit**, ${hits.length - bad.length} fit.\n\n`;
md2 += `## Pairs that do not fit\n\n`;
for (const h of bad.sort((a, b) => Math.abs(Math.log(b.miles / (b.days * 20))) - Math.abs(Math.log(a.miles / (a.days * 20))))) {
  md2 += `- **${h.from} ↔ ${h.to}**: notes say ${h.days} day(s)${h.by === 'sea' ? ' by sea' : ''}; the map has ${Math.round(h.miles)} mi (${(h.miles / h.days).toFixed(0)} mi/day) — ${h.verdict}. ${h.guess.length ? `Placed by me as a first-pass guess: ${h.guess.join(', ')}.` : 'Both places come from your maps or placements.'}\n  > ${h.sentence}\n`;
}
md2 += `\n## Pairs that fit\n\n${hits.filter((h) => h.verdict === 'fits').map((h) => `- ${h.from} ↔ ${h.to}: ${h.days} day(s), ${Math.round(h.miles)} mi (${(h.miles / h.days).toFixed(0)} mi/day)`).join('\n') || '_none_'}\n`;
fs.writeFileSync('source/audit_travel.md', md2);
console.log(`travel pairs ${hits.length}: fit ${hits.length - bad.length}, do not fit ${bad.length}`);
