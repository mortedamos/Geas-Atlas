// Reconcile the map with the database in both directions and write tools/source/gazetteer.md:
//   1. places on the map that have no (canon) write-up
//   2. canon write-ups that are not on the map, grouped by where they sit in the world
// usage: node gazetteer.mjs ../atlas/data
import fs from 'node:fs';
import path from 'node:path';

const dataDir = path.resolve(process.argv[2] || '../atlas/data');
const objs = JSON.parse(fs.readFileSync('../original_data/db/objects.json', 'utf8'));
const policy = JSON.parse(fs.readFileSync('source/canon_policy.json', 'utf8'));
const byId = new Map(objs.map((o) => [o.id, o]));
const byName = new Map(objs.filter((o) => ['place', 'group'].includes(o.type)).map((o) => [o.name.toLowerCase(), o]));
const thirdParty = new Set(policy.thirdPartyOwners.ids);
const isCanon = (o) => !thirdParty.has(o.owner) && policy.canonOwners.includes(o.owner) && (o.modowner === '' || policy.includeIfLastEditedBy.includes(Number(o.modowner)));

const parentOf = (o) => { const g = (o.parentgroup || '').trim(); return !g ? null : /^\d+$/.test(g) ? byId.get(Number(g)) : byName.get(g.toLowerCase()); };
function trail(o) { const out = []; let c = parentOf(o), n = 0; while (c && n++ < 8) { out.unshift(c.name); c = parentOf(c); } return out.filter((x) => !/^(ourgos)$/i.test(x)); }

const features = ['places', 'regions'].flatMap((f) => JSON.parse(fs.readFileSync(path.join(dataDir, `${f}.geojson`), 'utf8')).features);
const linkedIds = new Set(features.filter((f) => f.properties.dbId).map((f) => f.properties.dbId));
// rivers are drawn as lines, not pins: a river whose name matches a database place counts as on the map
const riverNames = new Set(JSON.parse(fs.readFileSync(path.join(dataDir, 'rivers.geojson'), 'utf8')).features.flatMap((f) => { const n = (f.properties.name || '').toLowerCase(); return [n, n.replace(/^river /, '')]; }).filter(Boolean));
for (const o of objs) if (o.type === 'place' && riverNames.has(o.name.toLowerCase())) linkedIds.add(o.id);
const unlinkedOnMap = features.filter((f) => !f.properties.dbId && f.properties.rank).map((f) => f.properties);

const canonPlaces = objs.filter((o) => o.type === 'place' && isCanon(o));
const notOnMap = canonPlaces.filter((o) => !linkedIds.has(o.id));

// group by the continent/realm: the child of "Geas" (or the first element of the trail)
const groups = {};
for (const o of notOnMap) {
  const t = trail(o);
  const i = t.findIndex((x) => /^geas$/i.test(x));
  const realm = i >= 0 ? t[i + 1] || '(Geas itself)' : t[0] || '(top level)';
  const sub = i >= 0 ? t.slice(i + 2) : t.slice(1);
  (groups[realm] ||= []).push({ name: o.name, sub: sub.join(' › '), id: o.id, blurb: (o.shortdesc || '').replace(/\s+/g, ' ').slice(0, 90) });
}

let md = '# Gazetteer: map vs. database\n\nGenerated by tools/gazetteer.mjs. Canon policy: tools/source/canon_policy.json.\n\n';
md += `- Places on the map: ${features.filter((f) => f.properties.rank).length}; linked to a database entry: ${linkedIds.size}\n`;
md += `- Canon places in the database: ${canonPlaces.length}; **not on the map yet: ${notOnMap.length}**\n\n`;
md += `## On the map but never written up (${unlinkedOnMap.length})\n\nThese exist only as labels on the hand-drawn maps. Names were read from hand lettering, so some may also be misspelt versions of entries that do exist.\n\n`;
const bySrc = {};
for (const p of unlinkedOnMap) (bySrc[p.source] ||= []).push(`${p.name}${p.kind ? ` (${p.kind})` : ''}`);
for (const [src, list] of Object.entries(bySrc)) md += `**${src}:** ${list.join(', ')}\n\n`;
md += `## Written up but not on the map (${notOnMap.length})\n\n`;
for (const [realm, list] of Object.entries(groups).sort((a, b) => b[1].length - a[1].length)) {
  md += `### ${realm} (${list.length})\n`;
  for (const p of list.sort((a, b) => (a.sub + a.name).localeCompare(b.sub + b.name))) md += `- ${p.sub ? `${p.sub} › ` : ''}**${p.name}**${p.blurb ? ` — ${p.blurb}` : ''}\n`;
  md += '\n';
}
fs.writeFileSync('source/gazetteer.md', md);
// machine-readable list for the viewer's placement mode (served only by the local dev server)
fs.writeFileSync('source/unplaced.json', JSON.stringify(Object.entries(groups).flatMap(([realm, list]) => list.map((p) => ({ id: p.id, name: p.name, realm, sub: p.sub, blurb: p.blurb }))).sort((a, b) => (a.realm + a.sub + a.name).localeCompare(b.realm + b.sub + b.name))));
console.log('on map:', features.filter((f) => f.properties.rank).length, 'linked:', linkedIds.size, '| never written up:', unlinkedOnMap.length, '| canon places not on map:', notOnMap.length);
console.log(Object.entries(groups).sort((a, b) => b[1].length - a[1].length).map(([r, l]) => `${r}: ${l.length}`).join('\n'));
